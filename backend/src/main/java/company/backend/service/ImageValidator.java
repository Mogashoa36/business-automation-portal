package company.backend.service;

import java.awt.image.BufferedImage;
import java.io.ByteArrayInputStream;
import java.io.IOException;
import java.io.InputStream;
import java.util.List;
import java.util.Locale;

import javax.imageio.ImageIO;

/**
 * Validates an uploaded file as a genuine image.
 *
 * <p>Trusting the filename extension or the {@code Content-Type} a client
 * sends is the classic way to get an executable or a script onto a server. This
 * class trusts neither. It:
 *
 * <ol>
 * <li>checks the declared MIME type against a configured allow list,
 * <li>reads the file's magic bytes, which must agree with that type, and
 * <li>fully decodes the image, so a file that is not really an image fails here
 * rather than in a browser.</li>
 * </ol>
 *
 * <p>A file that passes all three is an image the JDK can decode, which rules
 * out scripts, HTML, SVG and executables without maintaining a block list.
 */
public final class ImageValidator {

	/** MIME types the portal accepts. */
	public static final List<String> ALLOWED_MIME_TYPES = List.of("image/jpeg", "image/png", "image/gif",
			"image/webp");

	/** Extension to use for each allowed type. Fixed by the type, never by the client. */
	private static final String JPEG = "image/jpeg";
	private static final String PNG = "image/png";
	private static final String GIF = "image/gif";
	private static final String WEBP = "image/webp";

	private ImageValidator() {
		// Utility class.
	}

	/** @return the canonical MIME type, or {@code null} when not permitted */
	public static String resolveMimeType(String declaredType) {
		if (declaredType == null) {
			return null;
		}
		// Strips any ";charset=..." suffix and lower cases, because the header
		// is client supplied and may be padded in ways a browser would tolerate.
		String normalised = declaredType.split(";")[0].trim().toLowerCase(Locale.ROOT);
		return ALLOWED_MIME_TYPES.contains(normalised) ? normalised : null;
	}

	/**
	 * @return the file extension to store, for example {@code png}
	 * @throws IllegalArgumentException when the type is not allowed
	 */
	public static String extensionFor(String mimeType) {
		return switch (mimeType) {
			case JPEG -> "jpg";
			case PNG -> "png";
			case GIF -> "gif";
			case WEBP -> "webp";
			default -> throw new IllegalArgumentException("Unsupported image type: " + mimeType);
		};
	}

	/**
	 * Confirms the leading bytes match the declared type.
	 *
	 * <p>This is a cheap first gate before the expensive decode, and it catches a
	 * renamed file immediately.
	 */
	public static boolean magicBytesMatch(byte[] header, String mimeType) {
		if (header == null || header.length < 12) {
			return false;
		}
		return switch (mimeType) {
			case JPEG -> (header[0] & 0xFF) == 0xFF && (header[1] & 0xFF) == 0xD8 && (header[2] & 0xFF) == 0xFF;
			case PNG -> (header[0] & 0xFF) == 0x89 && header[1] == 'P' && header[2] == 'N' && header[3] == 'G';
			case GIF -> header[0] == 'G' && header[1] == 'I' && header[2] == 'F' && header[3] == '8';
			// RIFF....WEBP
			case WEBP -> header[0] == 'R' && header[1] == 'I' && header[2] == 'F' && header[3] == 'F'
					&& header[8] == 'W' && header[9] == 'E' && header[10] == 'B' && header[11] == 'P';
			default -> false;
		};
	}

	/**
	 * Fully decodes the image and returns its dimensions.
	 *
	 * @return the decoded image's {@code [width, height]}, or {@code null} when
	 * the bytes are not a decodable image
	 */
	public static int[] decode(byte[] bytes) {
		try (InputStream in = new ByteArrayInputStream(bytes)) {
			BufferedImage image = ImageIO.read(in);
			return image == null ? null : new int[] { image.getWidth(), image.getHeight() };
		}
		catch (IOException | RuntimeException exception) {
			// Any failure to decode means we do not trust the file. Runtime
			// exceptions are included because some malformed images throw
			// rather than returning null.
			return null;
		}
	}

	/**
	 * Reduces a caller supplied filename to a harmless display label.
	 *
	 * <p>Only the final path segment survives, so no directory component can be
	 * forged, and everything outside a conservative character set is replaced.
	 * The result is only ever displayed and logged - it is never used to build a
	 * path. Stored names are always generated by {@link #generatedFileName}.
	 */
	public static String sanitiseFileName(String candidate) {
		if (candidate == null || candidate.isBlank()) {
			return "image";
		}
		// Takes only the final path segment, so "../x" and "a/b" both reduce to
		// the last component before any characters are stripped.
		String leaf = candidate.replace('\\', '/');
		int lastSlash = leaf.lastIndexOf('/');
		if (lastSlash >= 0) {
			leaf = leaf.substring(lastSlash + 1);
		}
		String cleaned = leaf.replaceAll("[^A-Za-z0-9._-]", "-")
			.replaceAll("-{2,}", "-")
			.replaceAll("^[.-]+", "");
		return cleaned.isBlank() ? "image" : cleaned;
	}

	/** A filesystem and URL safe name derived from a random identifier. */
	public static String generatedFileName(String mimeType) {
		return java.util.UUID.randomUUID().toString().replace("-", "") + "." + extensionFor(mimeType);
	}
}